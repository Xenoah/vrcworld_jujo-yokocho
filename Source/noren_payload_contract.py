def enabled(manifest):
    features = manifest.get('features', {})
    return isinstance(features, dict) and features.get('noren_craft') is True


def rows(payloads):
    return {(r[0], r[1]): dict(zip(FIELDS, r[2:])) for r in payloads}


def validate_schema(peer_baseline):
    """Fail closed for exact original, removal, addition and after identities."""
    try:
        exact = (hashlib.sha256(json.dumps(APPROVED_PAYLOADS, separators=(',', ':')).encode()).hexdigest()
                 == APPROVED_PAYLOADS_SCHEMA_SHA256
                 and hashlib.sha256(json.dumps(PRESERVED_SLICES, separators=(',', ':')).encode()).hexdigest()
                 == PRESERVED_SLICES_SCHEMA_SHA256)
    except (TypeError, ValueError):
        exact = False
    if not exact:
        raise ValueError('Invalid explicit noren Identity revision schema')
    old, after = rows(ORIGINAL_PAYLOADS), rows(APPROVED_PAYLOADS)
    unprotected = {tuple(k) for k in peer_baseline['unprotectedBatchKeys']}
    core = {(r['group'], r['material']) for r in peer_baseline['protectedGroups']}
    if (len(ORIGINAL_PAYLOADS) != 56 or set(old) != set(ORIGINAL_KEYS)
            or not set(old) <= unprotected or set(old) & core
            or set(ADDED_KEYS) & (unprotected | core)
            or not set(REMOVED_KEYS) <= set(old) or set(REMOVED_KEYS) & core
            or len(APPROVED_PAYLOADS) != 59
            or set(after) != (set(old) - set(REMOVED_KEYS)) | set(ADDED_KEYS)
            or {k for k in old.keys() & after.keys() if old[k] == after[k]} != set(UNCHANGED_KEYS)
            or len(PRESERVED_SLICES) != 107
            or len({tuple(r[:3]) for r in PRESERVED_SLICES}) != 107):
        raise ValueError('Invalid explicit noren Identity revision schema')
    for record in ORIGINAL_PAYLOADS + APPROVED_PAYLOADS:
        if (any(type(v) is not int or v <= 0 for v in record[2:4])
                or any(not isinstance(h, str) or len(h) != 64
                       or any(c not in '0123456789abcdef' for c in h) for h in record[4:])):
            raise ValueError('Invalid explicit noren Identity revision schema')
    return after


def load_baseline(root):
    path = Path(root) / 'Docs/baselines' / BASELINE_NAME
    try:
        raw = path.read_bytes()
    except OSError as error:
        raise ValueError('Missing frozen v2.11 original-Identity baseline file') from error
    if hashlib.sha256(raw).hexdigest() != BASELINE_SHA256:
        raise ValueError('Frozen v2.11 original-Identity baseline file hash changed')
    baseline = json.loads(raw)
    try:
        original = tuple(tuple(r[f] for f in ('group', 'material') + FIELDS)
                         for r in baseline['originalIdentityGroups'])
        fields = ('group', 'material', 'component', 'vertexStart', 'triangleStart',
                  'vertexCount', 'triangleCount', 'geometrySha256', 'attributesAndIndicesSha256')
        slices = sorted(tuple(r[f] for f in fields) for r in baseline['originalPreservedComponents'])
        if (type(baseline['schemaVersion']) is not int or baseline['schemaVersion'] != 1
                or baseline['sourceVersion'] != '2.11.0'
                or baseline['sourceNativeVisualSha256'] != 'c41888a0dcb663f9fa08ef411c3c6ed09317d5b173b921e5f10721b83b9d5d71'
                or original != ORIGINAL_PAYLOADS
                or slices != sorted(tuple(r[:9]) for r in PRESERVED_SLICES)):
            raise ValueError('Original-Identity code pins differ from frozen archive baseline')
    except (KeyError, TypeError) as error:
        raise ValueError('Invalid frozen original-Identity baseline schema') from error
    return baseline


def validate_native_slices(batches):
    """Exact explicit ranges, no searching, reordering, tolerance or regeneration."""
    by_key = {}
    for batch in batches:
        pair = (batch['group'], batch['material'])
        by_key.setdefault(pair, []).append(batch)
    errors, matched = [], 0
    for group, material, component, old_v, old_f, nv, nt, geometry, payload, vs, fs in PRESERVED_SLICES:
        label = (group, material, component)
        candidates = by_key.get((group, material), [])
        if len(candidates) != 1:
            errors.append(dict(reason='Preserved noren component batch missing or duplicated', component=label))
            continue
        b = candidates[0]
        try:
            if (any(type(v) is not int for v in (vs, fs, nv, nt)) or min(vs, fs) < 0
                    or min(nv, nt) <= 0 or vs + nv > len(b['vertices']) or fs + nt > len(b['faces'])):
                raise ValueError('Preserved noren component range invalid')
            faces = np.asarray(b['faces'][fs:fs+nt], dtype=np.int64)
            if np.any(faces < vs) or np.any(faces >= vs + nv):
                raise ValueError('Preserved noren component indices cross vertex span')
            v = np.asarray(b['vertices'][vs:vs+nv], dtype='<f4').tobytes()
            uv = np.asarray(b['uv'][vs:vs+nv], dtype='<f4').tobytes()
            colors = np.asarray(b['colors'][vs:vs+nv], dtype='u1').tobytes()
            local_indices = (faces-vs).astype('<u4').tobytes()
            if (hashlib.sha256(v+local_indices).hexdigest() != geometry
                    or hashlib.sha256(v+uv+colors+local_indices).hexdigest() != payload):
                raise ValueError('Preserved noren component payload changed')
            matched += 1
        except (ValueError, TypeError, IndexError) as error:
            errors.append(dict(reason=str(error), component=label))
    return not errors, dict(exactPreservedNorenComponentSlices=matched,
                           expectedPreservedNorenComponentSlices=107, errors=errors)
